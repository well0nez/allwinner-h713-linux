# third-party.py - THIRD-PARTY.md: the crates linked into the board's two programs, with their licences.
#
#   tools/third-party.py [OUT]        default THIRD-PARTY.md next to Cargo.toml
#
# The MIT and Apache-2.0 crates under h713-airplay ask for their notices to travel with the binaries; the image
# installs this file next to the README. The list is cargo's own resolve for aarch64-unknown-linux-gnu, walked
# from the two binaries' packages over normal (not dev, not build) dependencies; every licence file a crate ships
# (LICENSE*, LICENCE*, COPYING*, NOTICE*) is copied in once, identical texts shared. Run it after a dependency
# changes; `make notices` does.
import json, os, subprocess, sys

ROOTS = ("h713-airplay", "h713-airplay-presenter")
TARGET = "aarch64-unknown-linux-gnu"


def main():
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "THIRD-PARTY.md")
    meta = json.loads(subprocess.run(["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET],
                                     cwd=here, check=True, capture_output=True, text=True).stdout)
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    members = set(meta["workspace_members"])
    todo = [pid for pid, p in pkgs.items() if p["name"] in ROOTS and pid in members]
    if len(todo) != len(ROOTS):
        sys.exit(f"third-party.py: not all of {ROOTS} are workspace members")
    seen = set()
    while todo:
        pid = todo.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for d in nodes[pid]["deps"]:
            if any(k["kind"] is None for k in d["dep_kinds"]):
                todo.append(d["pkg"])
    crates = sorted((pkgs[p] for p in seen if p not in members), key=lambda p: (p["name"], p["version"]))
    texts, order, rows = {}, [], []
    for p in crates:
        d = os.path.dirname(p["manifest_path"])
        refs = []
        for f in sorted(os.listdir(d)):
            if f.upper().startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE")) and os.path.isfile(os.path.join(d, f)):
                t = open(os.path.join(d, f), encoding="utf-8", errors="replace").read().strip()
                if t not in texts:
                    texts[t] = f"T{len(texts) + 1}"
                    order.append(t)
                refs.append(f"{f} ({texts[t]})")
        lic = p.get("license") or ("see " + p["license_file"] if p.get("license_file") else "not stated")
        rows.append(f"| {p['name']} | {p['version']} | {lic} | {p.get('repository') or '-'} | {', '.join(refs) or '-'} |")
    with open(out, "w") as f:
        f.write("# Third-party crates in h713-airplay and h713-airplay-show\n\n"
                f"Generated by tools/third-party.py from Cargo.lock for {TARGET}; do not edit by hand.\n"
                "The programs themselves are GPL-3.0-only (README.md); crates/fairplay carries fcast's apple-fairplay "
                "(GPL-3.0-only, crates/fairplay/NOTICE). FFmpeg, libva, ALSA, Mesa (EGL, GLES, GBM) and glibc are the "
                "image's own Debian packages, linked at run time, with their notices in /usr/share/doc.\n\n"
                "| crate | version | licence | repository | licence files |\n|---|---|---|---|---|\n")
        f.write("\n".join(rows) + "\n")
        for t in order:
            f.write(f"\n## {texts[t]}\n\n```\n{t}\n```\n")
    print(f"third-party.py: {len(crates)} crates, {len(order)} licence texts -> {out}")


if __name__ == "__main__":
    main()
