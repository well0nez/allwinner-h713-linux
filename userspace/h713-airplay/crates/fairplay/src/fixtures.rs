#[cfg(test)]
mod tests {
    use super::HANDSHAKES;
    use crate::FairPlay;

    #[test]
    fn handshakes_replay_to_their_keys() {
        for h in HANDSHAKES {
            let mut fp = FairPlay::new();
            assert_eq!(fp.setup(&h.message1).unwrap()[13], h.mode);
            assert_eq!(fp.setup(&h.message3).unwrap()[12..], h.message3[144..]);
            assert_eq!(fp.decrypt_key(&h.ekey).unwrap(), h.key, "mode {}", h.mode);
        }
    }
}
